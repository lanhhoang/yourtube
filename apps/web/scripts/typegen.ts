import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src/lib/api.gen.ts");
const server = join(root, "../server");

const schema = execFileSync(
  "uv",
  ["run", "--directory", server, "python", "-m", "app.openapi_export"],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], maxBuffer: 64 * 1024 * 1024 },
);
const ast = await openapiTS(JSON.parse(schema));
const output = `// Generated by scripts/typegen.ts. Do not edit.\n${astToString(ast)}`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== output) {
    console.error("api.gen.ts is out of date. Run pnpm typegen.");
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
